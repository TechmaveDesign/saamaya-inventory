    function toggleSubmitContainer() {
    const radios = document.querySelectorAll('input[name="radio-group"]');
    const container = document.getElementById('FormSubmit_fix_container');
    let isChecked = false;

    // Check if any radio button is checked
    radios.forEach(radio => {
        if (radio.checked) {
            isChecked = true;
        }
    });

    // Toggle the visibility of the container
    container.style.display = isChecked ? 'flex' : 'none';
}
</script>
